    void draw()
    {
        system("clear");
        for (const string &row : maze)
        {
            for (char c : row)
            {
                if (c == '#')
                {
                    cout << "█";
                }
                else
                {
                    cout << c;
                }
            }
            cout << "\n";
        }

        if (!gameWon)
            cout << "\nMove (W/A/S/D) and press Enter: ";
    }

    void movePlayer(int dx, int dy)
    {
        int nextX = playerX + dx;
        int nextY = playerY + dy;
        // Check for the exit
        if (maze[nextY][nextX] == 'E')
        {
            gameWon = true;
            maze[playerY][playerX] = ' ';
            maze[nextY][nextX] = 'P';
        }
        // Check for uncrossable walls
        else if (maze[nextY][nextX] != '#')
        {
            maze[playerY][playerX] = ' ';
            playerX = nextX;
            playerY = nextY;
            maze[playerY][playerX] = 'P';
        }
    }

    // Reads user input and translates
    void processInput()
    {
        char input;
        cin >> input;
        input = tolower(input);
        if (input == 'w')
            movePlayer(0, -1);
        else if (input == 's')
            movePlayer(0, 1);
        else if (input == 'a')
            movePlayer(-1, 0);
        else if (input == 'd')
            movePlayer(1, 0);
    }

    bool isOver()
    {
        return gameWon;
    }
