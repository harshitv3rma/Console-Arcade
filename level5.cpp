int main()
{
    MazeGame game;
    MazeGame *ptr = &game;
    while (!ptr->isOver())
    { // POINTER to object
        ptr->draw();
        ptr->processInput();
    }
    ptr->draw();
    cout << "\nCongratulations! You escaped the maze!\n";
    return 0;
}
